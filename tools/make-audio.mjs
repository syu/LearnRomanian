// Downloads a Romanian recording (Google Translate voice) for every word and example
// sentence in words.js into audio/, and writes audio/index.js with the text → file map.
// Only missing files are downloaded; recordings no longer used are deleted.
//
//   node tools/make-audio.mjs

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, unlinkSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const audioDir = join(root, 'audio');
mkdirSync(audioDir, { recursive: true });

const ctx = { window: {} };
vm.runInNewContext(readFileSync(join(root, 'words.js'), 'utf8'), ctx);
const texts = new Set(['Afară plouă.']);   // used by the voice test button
for (const t of ctx.window.TOPICS) {
  for (const w of t.words) {
    if (w.audio) continue;
    texts.add(w.ro);
    if (w.ex) texts.add(w.ex);
  }
}

const slug = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()
  .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60) || 'x';

// keep earlier file names stable
const indexPath = join(audioDir, 'index.js');
const prev = {};
if (existsSync(indexPath)) {
  const c = { window: {} };
  vm.runInNewContext(readFileSync(indexPath, 'utf8'), c);
  Object.assign(prev, c.window.AUDIO || {});
}

const map = {};
const used = new Set();
for (const text of texts) {
  if (prev[text]) { map[text] = prev[text]; used.add(prev[text]); }
}
for (const text of texts) {
  if (map[text]) continue;
  let name = slug(text), file, n = 1;
  do { file = `audio/${name}${n > 1 ? '-' + n : ''}.mp3`; n++; } while (used.has(file));
  map[text] = file; used.add(file);
}

const sleep = ms => new Promise(r => setTimeout(r, ms));
let downloaded = 0, failed = [];
for (const [text, file] of Object.entries(map)) {
  const path = join(root, file);
  if (existsSync(path) && statSync(path).size > 1000) continue;
  const url = 'https://translate.google.com/translate_tts?ie=UTF-8&client=tw-ob&tl=ro&q=' + encodeURIComponent(text);
  let ok = false;
  for (let attempt = 1; attempt <= 3 && !ok; attempt++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0' } });
      const buf = Buffer.from(await res.arrayBuffer());
      if (res.ok && /audio/.test(res.headers.get('content-type') || '') && buf.length > 1000) {
        writeFileSync(path, buf); ok = true; downloaded++;
      } else await sleep(1500 * attempt);
    } catch { await sleep(1500 * attempt); }
  }
  if (!ok) { failed.push(text); delete map[text]; }
  await sleep(250);
}

// remove recordings that are no longer used
let removed = 0;
const keep = new Set(Object.values(map).map(f => f.replace('audio/', '')));
for (const f of readdirSync(audioDir)) {
  if (f.endsWith('.mp3') && !keep.has(f)) { unlinkSync(join(audioDir, f)); removed++; }
}

const sorted = Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b, 'ro')));
writeFileSync(indexPath,
  '// Generated by tools/make-audio.mjs — do not edit by hand.\n' +
  'window.AUDIO = ' + JSON.stringify(sorted, null, 1) + ';\n');

console.log(`${Object.keys(map).length} recordings, ${downloaded} downloaded, ${removed} removed`);
if (failed.length) { console.log('Failed:', failed.join(' | ')); process.exitCode = 1; }
